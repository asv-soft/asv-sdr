    public static void InitLookupTables()
    {
        for (var i = 0; i < 256; ++i)
        {
            var c = (uint)(i << 16);
            int j;
            for (j = 0; j < 8; ++j)
            {
                if ((c & 0x800000) != 0)
                    c = (c << 1) ^ Generator;
                else
                    c <<= 1;
            }

            Crc24Table[i] = c & 0x00FFFFFF;
        }
    }


    /// <summary>
    /// Calculate ADS-B Message CRC
    /// </summary>
    /// <param name="message"></param>
    /// <param name="length"></param>
    /// <returns></returns>
    public static uint CalcCrc24(ReadOnlySpan<byte> message, int length)
    {
        uint crc = 0;
        int i;
        var n = length;

        for (i = 0; i < n; ++i)
        {
            crc = (crc << 8) ^ Crc24Table[message[i] ^ ((crc & 0xFF0000) >> 16)];
            crc &= 0x00FFFFFF;
        }

        return crc;

        // return (uint)(rem ^ (message[n - 3] << 16) ^ (message[n - 2] << 8) ^ (message[n - 1]));
    }


    /// <summary>
    /// Check crc for message
    /// </summary>
    /// <param name="message"></param>
    /// <returns></returns>
    public static uint ModesCheckSum(ReadOnlySpan<byte> message)
    {
        var n = message.Length;
        var crc = CalcCrc24(message, message.Length - 3);
        return (uint)(crc ^ (message[n - 3] << 16) ^ (message[n - 2] << 8) ^ message[n - 1]);
    }

    public static uint GetModeSFormat(ReadOnlySpan<byte> message)
    {
        var pos = 0;
        return GetBitU(message, ref pos, 5);
    }

    public static void SetModeSFormat(Span<byte> message, uint format)
    {
        var pos = 0;
        SetBitU(message, ref pos, 5, format & 0x1F);
    }

