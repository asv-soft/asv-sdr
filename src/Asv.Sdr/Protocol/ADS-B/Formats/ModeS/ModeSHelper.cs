    // Извлечение диапазона битов с начальной позиции и длиной
    public static uint GetBitU(byte[] msg, ref int bitPos, int length)
    {
        if (length > 32)
            throw new ArgumentException("Длина не должна превышать 32 бита");

        uint result = 0;
        for (var i = bitPos; i < length + bitPos; i++)
        {
            result = (result << 1) | (uint)((msg[i / 8] >> (7 - i % 8)) & 0x1);
        }

        bitPos += length; // Опционально: обновление позиции
        return result;
    }

    // Извлечение диапазона битов с начальной позиции и длиной
    public static uint GetBitU(ReadOnlySpan<byte> msg, ref int bitPos, int length)
    {
        if (length > 32)
            throw new ArgumentException("Длина не должна превышать 32 бита");

        uint result = 0;
        for (var i = bitPos; i < length + bitPos; i++)
        {
            result = (result << 1) | (uint)((msg[i / 8] >> (7 - i % 8)) & 0x1);
        }

        bitPos += length; // Опционально: обновление позиции
        return result;
    }

    // Установка диапазона битов с начальной позиции и длиной
    public static void SetBitU(byte[] msg, ref int bitPos, int length, uint value)
    {
        if (length > 32)
            throw new ArgumentException("Длина не должна превышать 32 бита");

        if (value >= (1U << (int)length))
            throw new ArgumentException($"Значение {value} превышает максимум для {length} бит");

        var shift = 1U << length - 1;
        for (var i = bitPos; i < length + bitPos; i++)
        {
            if ((value & shift) != 0)
                msg[i / 8] |= (byte)(1 << 7 - i % 8); // Установить бит в 1
            else
                msg[i / 8] &= (byte)~(1 << 7 - i % 8); // Установить бит в 0
            shift >>= 1;
        }

        bitPos += length; // Опционально: обновление позиции
    }
    
    public static int GetBitS(ReadOnlySpan<byte> buff, ref int pos, int len)
    {
        var bitU = GetBitU(buff, ref pos, len);
        return len <= 0 || 32 /*0x20*/ <= len || ((int) bitU & 1 << len - 1) == 0 ? (int) bitU : (int) bitU | -1 << len;
    }
    
    public static void SetBitS(Span<byte> buff, ref int pos, int len, int data)
    {
        if (data < 0)
            data |= 1 << len - 1;
        else
            data &= ~(1 << len - 1);
        SetBitU(buff, ref pos, len, (uint) data);
    }

